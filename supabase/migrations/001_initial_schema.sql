create type public.project_status as enum ('draft', 'published', 'archived');


-- ─────────────────────────────────────────────
-- 1. UTILITY: updated_at auto-trigger
-- ─────────────────────────────────────────────

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;


-- ─────────────────────────────────────────────
-- 2. USERS TABLE
--    Mirrors auth.users — one row per signed-up user.
--    Populated automatically by the handle_new_user trigger below.
-- ─────────────────────────────────────────────

create table public.users (
  id           uuid        primary key references auth.users (id) on delete cascade,
  email        text        not null,
  full_name    text,
  avatar_url   text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- Automatically update updated_at on every row change
create trigger users_set_updated_at
  before update on public.users
  for each row execute function public.set_updated_at();

-- Auto-create a profile row whenever someone signs up via Supabase Auth
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.users (id, email, full_name, avatar_url)
  values (
    new.id,
    new.email,
    new.raw_user_meta_data ->> 'full_name',
    new.raw_user_meta_data ->> 'avatar_url'
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();


