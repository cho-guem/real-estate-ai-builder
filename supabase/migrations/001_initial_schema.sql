create table public.projects (
  id          uuid               primary key default gen_random_uuid(),
  user_id     uuid               not null references public.users (id) on delete cascade,
  name        text               not null,
  slug        text               not null,
  description text,
  status      public.project_status not null default 'draft',
  config      jsonb              not null default '{}'::jsonb,
  created_at  timestamptz        not null default now(),
  updated_at  timestamptz        not null default now(),

  constraint projects_slug_per_user unique (user_id, slug)
);

-- Auto update updated_at
create trigger projects_set_updated_at
  before update on public.projects
  for each row execute function public.set_updated_at();

-- Index for the most common query: all projects by a user, newest first
create index projects_user_id_created_at_idx
  on public.projects (user_id, created_at desc);

-- Index for slug lookups (public website routing)
create index projects_slug_idx
  on public.projects (slug);

